const fixtureModule = "example.com/dcm"

func TestBackendFollowsArchitectureContracts(t *testing.T) {
	t.Parallel()

	root, err := filepath.Abs(filepath.Join("..", ".."))
	require.NoError(t, err)

	report, err := checkTree(root)
	require.NoError(t, err)
	require.Positive(t, report.checkedFiles, "no Go files found under %s", root)
	for _, v := range report.violations {
		t.Error(v)
	}
	if t.Failed() {
		t.Log("Rules are documented in docs/agent-context/backend-contracts.md#architecture-enforcement.")
	}
}

